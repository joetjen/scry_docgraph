# Generator source for `lib/scry/docgraph/grammar/compiled.ex` -- that
# file is generated, checked in, and must never be hand-edited (see its
# own banner). Run this script (`mix run priv/gen/
# generate_compiled_grammar.exs`) after `scry_document`'s or
# `scry_graph`'s own `priv/grammar.aether` changes (this package has no
# fragment of its own to edit), then re-run the test suite. There's no
# automatic staleness check between the two -- see `scry_core`'s own
# identical generator script for why (a byte-diff between two
# separately-generated copies of the same grammar spuriously fails; the
# codegen backend iterates `%Aether.Grammar{}`'s own maps, whose
# iteration order isn't stable across VM boots). `grammar_parity_test.exs`
# is the safety net instead.
#
# Two fragments folded, not one -- `scry_document`'s and `scry_graph`'s
# own, in that order (`Scry.Core.GrammarCompose.merge/2`'s own moduledoc:
# "to compose more than one fragment, fold this over a list"). Fold
# order doesn't affect the result: `body_item_ep1` (the only rule name
# both fragments happen to fill) is an extension point, unioned not
# collided, and union is commutative up to alternative order (`Scry.
# DocGraph.Grammar`'s own moduledoc has the full "why this doesn't
# collide" story).

frag_paths = [Scry.Document.Grammar.grammar_path(), Scry.Graph.Grammar.grammar_path()]

{:ok, core} = Scry.Core.Grammar.compile_unanalyzed()

merged =
  Enum.reduce(frag_paths, core, fn frag_path, acc ->
    {:ok, fragment} = Aether.Parser.parse(File.read!(frag_path), frag_path)
    {:ok, merged} = Scry.Core.GrammarCompose.merge(acc, fragment)
    merged
  end)

body = Ichor.generate_from_grammar(merged, Scry.DocGraph.Actions)

# See `Scry.Core.Grammar`'s own generator script for what/why this does
# -- identical, `Mix.Tasks.Ichor.Gen`'s own `publicize/1`.
publicize = fn body ->
  Macro.postwalk(body, fn
    {:defp, meta, args} -> {:def, meta, args}
    other -> other
  end)
end

text =
  quote do
    defmodule Scry.DocGraph.Grammar.Compiled do
      @moduledoc false
      unquote(publicize.(body))
    end
  end
  |> Macro.to_string()
  |> Code.format_string!()
  |> IO.iodata_to_binary()

banner = """
# Generated by:
#
#     mix run priv/gen/generate_compiled_grammar.exs
#
# Do not edit by hand -- edit scry_document's/scry_graph's own
# priv/grammar.aether, then rerun the command above and the test suite
# instead.
"""

out = Path.join(__DIR__, "../../lib/scry/docgraph/grammar/compiled.ex") |> Path.expand()
File.mkdir_p!(Path.dirname(out))
File.write!(out, banner <> text <> "\n")
Mix.shell().info("* creating #{out}")
